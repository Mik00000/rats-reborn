	// ????????? ???? ?????? ?????????? Create; ????????? ??????, ?????, ???, ??????????? ? ????????, ?????? ????????? ????????? ??? ?????? ?????????.
	private static ApplicationResult resolveApplicationRecipe(RecipeHolder<?> holder, RecipeWrapper wrapper, ServerLevel level, RandomSource random, ItemStack held, ItemStack target) {
		try {
			Recipe<?> recipe = holder.value();
			if (!hasApplicationRecipeMethods(recipe)) {
				return ApplicationResult.empty();
			}
			if (!recipeMatches(recipe, wrapper, level)) {
				return ApplicationResult.empty();
			}
			List<ItemStack> outputs = getRecipeOutputs(recipe, wrapper, level, random);
			if (outputs.isEmpty()) {
				RatsMod.LOGGER.error("?????? Create {} ???????, ?? ?? ????? ????????? ??? {} + {}", holder.id(), target, held);
				return ApplicationResult.empty();
			}
			return new ApplicationResult(outputs, shouldKeepHeldItem(recipe), holder.id().toString());
		} catch (RuntimeException exception) {
			RatsMod.LOGGER.error("?? ??????? ????????? ?????? ?????????? Create {}", holder.id(), exception);
			throw exception;
		}
	}

