	@SuppressWarnings({"rawtypes", "unchecked"})
	private static List<ItemStack> getRecipeOutputs(Recipe<?> recipe, RecipeWrapper wrapper, ServerLevel level, RandomSource random) {
		try {
			List<ItemStack> results = new ArrayList<>();
			try {
				Optional<Method> rollResults = findOptionalMethod(recipe.getClass(), "rollResults", RandomSource.class);
				if (rollResults.isPresent()) {
					Object rolled = rollResults.get().invoke(recipe, random);
					if (rolled instanceof List<?> list) {
						for (Object object : list) {
							if (object instanceof ItemStack stack && !stack.isEmpty()) {
								results.add(stack.copy());
							}
						}
					}
				}
			} catch (IllegalAccessException | InvocationTargetException exception) {
				throw new IllegalStateException("?? ??????? ???????? ????????? ?????????? ??????? Create", exception);
			}
			if (results.isEmpty()) {
				ItemStack assembled = ((Recipe) recipe).assemble(wrapper, level.registryAccess());
				if (!assembled.isEmpty()) {
					results.add(assembled.copy());
				}
			}
			return results;
		} catch (RuntimeException exception) {
			RatsMod.LOGGER.error("?? ??????? ???????? ????????? ??????? Create {}", recipe, exception);
			throw exception;
		}
	}

