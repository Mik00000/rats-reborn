	// ????????? ???????? ?????????? Create ?? ????????; ????????? ??? ? ????, ?????? true ???? ???? ???????? ??? ?????? ??????? ??????? ??????????.
	public static boolean isKnownApplicationItem(Level level, ItemStack stack) {
		try {
			if (isKnownApplicationItem(stack)) {
				return true;
			}
			if (!(level instanceof ServerLevel serverLevel) || stack.isEmpty() || !RatsMod.CREATE_LOADED) {
				return false;
			}
			ensureRecipeCachesValid(serverLevel);
			String itemKey = getItemId(stack);
			Boolean cached = APPLICATION_ITEM_CACHE.get(itemKey);
			if (cached != null) {
				return cached;
			}
			for (RecipeHolder<?> holder : getDeployingRecipes(serverLevel)) {
				Recipe<?> recipe = holder.value();
				if (hasApplicationRecipeMethods(recipe) && ingredientAccepts(getRequiredHeldItem(recipe), stack)) {
					APPLICATION_ITEM_CACHE.put(itemKey, true);
					return true;
				}
			}
			for (RecipeHolder<?> holder : getSequencedAssemblyDefinitions(serverLevel)) {
				for (Recipe<?> recipe : getSequencedAssemblyStepRecipes(holder.value())) {
					if (hasApplicationRecipeMethods(recipe) && ingredientAccepts(getRequiredHeldItem(recipe), stack)) {
						APPLICATION_ITEM_CACHE.put(itemKey, true);
						return true;
					}
				}
			}
			APPLICATION_ITEM_CACHE.put(itemKey, false);
			return false;
		} catch (RuntimeException exception) {
			RatsMod.LOGGER.error("?? ??????? ????????? ???????? ?????????? Create {} ?? ????????", stack, exception);
			throw exception;
		}
	}

