	// ????????? ???????? ????? ? ???????? ?? ????? Create; ????????? ?????, ??? ? ???????, ?????? true ??? ???????? ???????.
	private static boolean applyItemOnBelt(TamedRat rat, ServerLevel level, BlockPos pos) {
		try {
			BlockEntity sourceEntity = level.getBlockEntity(pos);
			BlockEntity beltEntity = resolveBeltBlockEntity(sourceEntity);
			if (beltEntity == null) {
				return false;
			}
			ItemStack held = rat.getMainHandItem();
			if (held.isEmpty()) {
				return false;
			}
			Object inventory = getBeltInventory(beltEntity);
			List<?> transportedItems = getTransportedItems(inventory);
			if (transportedItems.isEmpty()) {
				return false;
			}
			int targetSegment = getBeltSegmentIndex(sourceEntity);
			for (Object transported : new ArrayList<>(transportedItems)) {
				if (!isTransportedOnSegment(transported, targetSegment)) {
					continue;
				}
				ItemStack beltStack = getTransportedStack(transported);
				ApplicationResult result = getApplicationResult(level, rat.getRandom(), held, beltStack);
				if (result.results().isEmpty()) {
					continue;
				}
				if (!result.keepHeldItem()) {
					held.shrink(1);
				}
				applyBeltOutputs(level, inventory, transported, beltStack, result.results());
				markBeltInventoryDirty(beltEntity);
				if (sourceEntity != null && sourceEntity != beltEntity) {
					markBeltInventoryDirty(sourceEntity);
				}
				RatsMod.LOGGER.debug("????? {} ????????? {} ? {} ?? ????? {} ?? ??????? {}", rat.getUUID(), held, beltStack, pos, result.recipeId());
				return true;
			}
			return false;
		} catch (RuntimeException exception) {
			RatsMod.LOGGER.error("????? {} ?? ?????? ????????? ??????? ?? ????? Create {}", rat.getUUID(), pos, exception);
			throw exception;
		}
	}

	// ????????? ????????? ??????????; ????????? ???, ???????????, ??????? ? ????? ? ??????? ?? ?????, ?????? ????????? ??????? Create.
	private static ApplicationResult getApplicationResult(ServerLevel level, RandomSource random, ItemStack held, ItemStack target) {
		try {
			if (held.isEmpty() || target.isEmpty()) {
				return ApplicationResult.empty();
			}
			ensureRecipeCachesValid(level);
			RecipeWrapper wrapper = createRecipeWrapper(target, held);
			String matchKey = getApplicationMatchCacheKey(held, target);
			Optional<RecipeHolder<?>> cachedMatch = APPLICATION_MATCH_CACHE.get(matchKey);
			if (cachedMatch != null) {
				if (cachedMatch.isEmpty()) {
					return ApplicationResult.empty();
				}
				ApplicationResult cachedResult = resolveApplicationRecipe(cachedMatch.get(), wrapper, level, random, held, target);
				if (!cachedResult.results().isEmpty()) {
					return cachedResult;
				}
				APPLICATION_MATCH_CACHE.remove(matchKey);
			}
			for (RecipeHolder<?> holder : getSequencedAssemblyApplicationRecipes(level, target)) {
				if (!applicationRecipeAcceptsHeldItem(holder.value(), held)) {
					continue;
				}
				ApplicationResult result = resolveApplicationRecipe(holder, wrapper, level, random, held, target);
				if (!result.results().isEmpty()) {
					APPLICATION_MATCH_CACHE.put(matchKey, Optional.of(holder));
					return result;
				}
			}
			for (RecipeHolder<?> holder : getDeployingRecipes(level)) {
				if (!applicationRecipeAcceptsHeldItem(holder.value(), held)) {
					continue;
				}
				ApplicationResult result = resolveApplicationRecipe(holder, wrapper, level, random, held, target);
				if (!result.results().isEmpty()) {
					APPLICATION_MATCH_CACHE.put(matchKey, Optional.of(holder));
					return result;
				}
			}
			APPLICATION_MATCH_CACHE.put(matchKey, Optional.empty());
			return ApplicationResult.empty();
		} catch (RuntimeException exception) {
			RatsMod.LOGGER.error("?? ??????? ????????? ?????? ?????????? Create ??? {} ? {}", held, target, exception);
			throw exception;
		}
	}

